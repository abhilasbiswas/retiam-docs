    /**
     * Mathematical Cardioid Heart curve.
     * Generated parametrically:
     *   x = 16 * sin^3(t)
     *   y = 13*cos(t) - 5*cos(2t) - 2*cos(3t) - cos(4t)
     */
    public static getHeartPoints(samples: number = 256): Vec2[] {
        const points: Vec2[] = new Array(samples);
        const twoPi = Math.PI * 2;
        for (let i = 0; i < samples; i++) {
            const t = (i / samples) * twoPi;
            const sint = Math.sin(t);
            const x = 16 * sint * sint * sint;
            const y = 13 * Math.cos(t) - 5 * Math.cos(2 * t) - 2 * Math.cos(3 * t) - Math.cos(4 * t);
            points[i] = new Vec2(x, y);
        }
        return points;
    }

    /**
     * Five-pointed star polygon.
     */
    public static getStarPoints(samples: number = 10, outerRadius: number = 20, innerRadius: number = 8): Vec2[] {
        const points: Vec2[] = [];
        const count = samples;
        const step = Math.PI / count;
        for (let i = 0; i < 2 * count; i++) {
            const r = i % 2 === 0 ? outerRadius : innerRadius;
            const angle = i * step - Math.PI / 2;
            points.push(new Vec2(r * Math.cos(angle), r * Math.sin(angle)));
        }
        return points;
    }

